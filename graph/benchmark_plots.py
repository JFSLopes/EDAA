"""
Plot benchmark CSV files generated by Benchmark.cpp.

Usage:
    python3 plot_benchmarks.py

Expected input directory:
    ../benchmark/

Output:
    ../benchmark/plots/*.png
"""

from __future__ import annotations

from pathlib import Path
from typing import Optional

import matplotlib.pyplot as plt
import pandas as pd
import numpy as np


BENCHMARK_DIR = Path("../benchmark")
PLOTS_DIR = BENCHMARK_DIR / "plots"


def setup_style() -> None:
    """White-background plot style."""
    plt.rcParams.update({
        "figure.facecolor": "white",
        "axes.facecolor": "white",
        "savefig.facecolor": "white",
        "axes.edgecolor": "black",
        "axes.grid": True,
        "grid.alpha": 0.25,
        "grid.linestyle": "--",
        "font.size": 10,
        "axes.titlesize": 12,
        "axes.labelsize": 10,
        "legend.fontsize": 8,
        "figure.autolayout": False,
    })


def ensure_dirs() -> None:
    PLOTS_DIR.mkdir(parents=True, exist_ok=True)


def read_csv(name: str) -> Optional[pd.DataFrame]:
    path = BENCHMARK_DIR / name

    if not path.exists():
        print(f"[skip] Missing {path}")
        return None

    try:
        df = pd.read_csv(path)
    except pd.errors.EmptyDataError:
        print(f"[skip] Empty {path}")
        return None

    if df.empty:
        print(f"[skip] No rows in {path}")
        return None

    return df


def save_plot(filename: str) -> None:
    path = PLOTS_DIR / filename
    plt.savefig(path, dpi=180, bbox_inches="tight")
    plt.close()
    print(f"[ok] {path}")


def has_columns(df: pd.DataFrame, columns: list[str]) -> bool:
    return all(col in df.columns for col in columns)


def safe_filename(value) -> str:
    return str(value).replace(".", "_").replace(" ", "_").replace("/", "_")


def numeric(df: pd.DataFrame, cols: list[str]) -> pd.DataFrame:
    data = df.copy()

    for col in cols:
        if col in data.columns:
            data[col] = pd.to_numeric(data[col], errors="coerce")

    return data


def mean_by(
        df: pd.DataFrame,
        group_cols: list[str],
        value_cols: list[str],
) -> pd.DataFrame:
    data = numeric(df, value_cols)

    needed = group_cols + value_cols
    data = data.dropna(subset=[c for c in needed if c in data.columns])

    if data.empty:
        return data

    return data.groupby(group_cols, as_index=False)[value_cols].mean()


def find_col_value(
        df: pd.DataFrame,
        col: str,
        keywords: list[str],
) -> Optional[str]:
    if col not in df.columns:
        return None

    values = df[col].dropna().astype(str).unique()

    for keyword in keywords:
        for value in values:
            if keyword.lower() in value.lower():
                return value

    return None


def filter_name_contains(
        df: pd.DataFrame,
        col: str,
        keywords: list[str],
) -> pd.DataFrame:
    if col not in df.columns:
        return pd.DataFrame()

    pattern = "|".join(keywords)

    return df[
        df[col].astype(str).str.contains(pattern, case=False, regex=True)
    ].copy()


def is_brute_force_name(value) -> bool:
    name = str(value).lower()

    return (
            "brute" in name
            or "linear" in name
            or "array" in name
            or "naive" in name
    )


